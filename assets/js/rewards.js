// Motivation system (§8): stars, deterministic trophies, map region states.
// Pure functions are exported for tests; the record/read functions use
// storage.js.

import { loadState, getRewards, setRewards } from "./storage.js";

// Playable games lead: the album shelves and the gear's reset rows iterate
// this order, and a child looks for Lesewiese right under Einmaleins — not
// below three shelves of games that do not exist yet.
export const GAMES = ["einmaleins", "lesen", "rechnungen", "tippen", "vokabeln"];

// Which of them a child can actually play. The other three are stubs, and the
// map must not promise what the site cannot deliver: their regions are drawn
// under fog (§3.1). Move a name here the moment its game exists.
export const PLAYABLE = ["einmaleins", "lesen", "rechnungen"];
export const isPlayable = (game) => PLAYABLE.includes(game);

// Every game holds twelve trophies (§8.3).
export const TROPHIES_PER_GAME = 12;

// Trophy s (1-indexed) of a game is earned when THAT game's lifetime point
// counter reaches `THRESHOLDS[game][s-1]`. Deterministic, no randomness.
//
// The ladder is per game, because the games are not worth the same. There used
// to be one ladder for all five, tuned to the einmaleins economy: `lesen` was
// then budgeted at 18 points, so its trophies five through twelve — thresholds
// 29 to 112 — were unreachable forever, and its shelf could never fill.
//
// einmaleins keeps its hand-tuned numbers exactly, so no child loses a trophy
// they have already won. The three unbuilt games are generated by `ladderFor`,
// whose shape is the einmaleins ladder itself — `tests/rewards.test.js` asserts
// that `ladderFor(180)` reproduces these twelve numbers, which is what keeps the
// generator honest. lesen is hand-tuned too (see LESEN_LADDER).
const EINMALEINS_LADDER = [2, 6, 12, 20, 29, 39, 50, 62, 75, 88, 100, 112];

// lesen is a small game — 15 tiles for 12 trophies, where einmaleins has 25 —
// so the generated ladder handed its shelf out far too fast: the einmaleins
// curve starts at ~1 % (thresholds 1, 3, 6 over lesen's 90), and a single
// perfect Schwer round is worth 9, so ONE round dropped three trophies at once
// and the room filled after roughly one play-through. That read as a bug ("in
// the Pokalraum all the reading trophies show up right away").
//
// So lesen gets its own hand-tuned ladder, the einmaleins pattern of a small
// exact game. It de-clumps the front (a first Schwer round now buys two
// trophies, not three) and pushes the twelfth to the top of the "not a grind"
// band (62 of 90 ≈ 69 %, einmaleins' own fraction), so filling the shelf needs
// play across all three difficulties — Schwer alone (45) no longer suffices.
// tests/rewards.test.js pins it verbatim and guards the one-round property.
const LESEN_LADDER = [3, 7, 12, 17, 23, 29, 35, 41, 47, 52, 57, 62];

// rechnungen (108 points, §12.2) borrows lesen's hand-tuned shape scaled up by
// 108/90 rather than the generated einmaleins curve — which over 108 points
// starts at 1, 4, 7 and would drop three trophies from a single perfect Schwer
// round (9 points), flooding the Pokalraum on day one, the very bug
// LESEN_LADDER was written to avoid. The first rung stays at 3, so a child's
// very first perfect Leicht round (3 points) is still a trophy; a first perfect
// Schwer round buys two, not three, and the twelfth trophy sits at 74 of 108
// (≈ 69 %), so filling the shelf needs play across the modes — Schwer alone
// caps at 54. tests/rewards.test.js pins it verbatim and guards the one-round
// property.
const RECHNUNGEN_LADDER = [3, 8, 14, 20, 28, 35, 42, 49, 56, 62, 68, 74];

// What a game is worth in stars if a child masters every tile it offers (§8.3).
// It is the denominator of everything the map says about a region, so it must
// be right.
//
// einmaleins is exact: 5 Leicht tiles × 3 + 11 Mittel × 6 + 9 Schwer × 9 — a
// star is worth 1, 2 or 3 depending on the difficulty that won it. (Schwer
// lost its 1er and 10er tiles: nothing in them is hard, §10.2. Stars already
// won there stay banked in `pr`; only the ceiling moved.)
//
// lesen is exact too: 5 tiles per difficulty (four packs and an "Alle"), so
// 5 × 3 + 5 × 6 + 5 × 9 (§14.3) — `maxPoints()` in games/lesen/logic.js
// computes it from the real tiles, and tests/rewards.test.js holds the two
// together.
//
// rechnungen is exact as of shipping: six mode tiles (＋ − ×÷ 🧱 ⊞ 🎲) per
// difficulty, so 6 × 3 + 6 × 6 + 6 × 9 = 108 (§12.2) — `maxPoints()` in
// games/rechnungen/logic.js computes it, and tests/rewards.test.js holds the
// two together.
//
// **The other two (tippen, vokabeln) are still guesses.** Those games do not
// exist, and neither does their tile structure; these numbers were once
// "achievable stars × 2", from a star count that no longer exists. RECOMPUTE a
// game's maximum from its real tiles the day it ships, exactly as einmaleins'
// 180 was computed — until then its badge tiers and region states are scaled
// against a number nobody checked.
export const MAX_POINTS = {
  einmaleins: 162,
  rechnungen: 108,
  tippen: 240,
  vokabeln: 108,
  lesen: 90,
};

// The twelve thresholds as fractions of everything a game is worth. Read off
// the einmaleins ladder: the last trophy at 62 % of the maximum is a real goal
// and not a grind, and the first at ~1 % arrives in the first sitting.
const LADDER_SHAPE = EINMALEINS_LADDER.map((v) => v / 180);

// A game's ladder, scaled to what that game can pay. Strictly increasing by
// construction: a small game (lesen: 18 points) would otherwise round two
// thresholds onto the same number and hand out two trophies for one point.
export function ladderFor(maxPoints) {
  if (!(maxPoints >= TROPHIES_PER_GAME)) {
    throw new RangeError(`a game worth ${maxPoints} points cannot hold ${TROPHIES_PER_GAME} trophies`);
  }
  let prev = 0;
  return LADDER_SHAPE.map((f) => {
    prev = Math.max(Math.round(f * maxPoints), prev + 1);
    return prev;
  });
}

export const THRESHOLDS = {
  einmaleins: EINMALEINS_LADDER,
  rechnungen: RECHNUNGEN_LADDER,
  tippen: ladderFor(MAX_POINTS.tippen),
  vokabeln: ladderFor(MAX_POINTS.vokabeln),
  lesen: LESEN_LADDER,
};

