// Practice time, for the parents' view only (§20) — the child is never shown a
// clock (§10.3). Aggregated per difficulty, never per question: a per-fact
// timer would eat the state budget and tell a parent nothing the Leitner box
// does not already say.
//
// A round left open on a forgotten tab is not practice, so a single round can
// never contribute more than this.
export const MAX_ROUND_SECONDS = 900;

// The three difficulties are the site's only axis of worth (§10.2): anything
// that is not 0 (Leicht), 1 (Mittel) or 2 (Schwer) reads as Leicht, so a
// corrupt store can never pay more than the easiest tier.
export const clampDifficulty = (d) => ([0, 1, 2].includes(d) ? d : 0);

// One practice counter per difficulty, sanitized: whatever the store holds,
// what comes back is three non-negative integers. Shared with the parents'
// arithmetic (parentstats.js), which reads what `addPractice` writes.
export const practiceTriple = (v) =>
  Array.isArray(v) && v.length === 3
    ? v.map((n) => (Number.isFinite(n) && n > 0 ? Math.round(n) : 0))
    : [0, 0, 0];

// Pure: takes the game's stored state, returns the `tm`/`rd` to write back.
//
// A broken clock banks no time, but still banks the round. Capping a NaN or an
// Infinity to MAX_ROUND_SECONDS would quietly credit fifteen minutes of
// practice that never happened, and a parent would read it as fact.
export function addPractice(saved = {}, difficulty = 0, seconds = 0) {
  const d = clampDifficulty(difficulty);
  const tm = practiceTriple(saved.tm);
  const rd = practiceTriple(saved.rd);
  tm[d] += Number.isFinite(seconds) && seconds > 0
    ? Math.min(Math.round(seconds), MAX_ROUND_SECONDS)
    : 0;
  rd[d] += 1;
  return { tm, rd };
}

// Every game has 12 trophies, so this is the whole collection (§8.3). It counts
// the four games that do not exist yet: the island promises six regions, and
// the Pokalraum promises what the island does.
export const TOTAL_TROPHIES = GAMES.length * TROPHIES_PER_GAME;

// ---- pure functions -------------------------------------------------------

// How many of `game`'s trophies its lifetime point counter has earned. The game
// must be named: a point is worth a different trophy in a different region.
export function trophyCount(game, pr) {
  const ladder = THRESHOLDS[game];
  if (!ladder) return 0;
  let n = 0;
  while (n < ladder.length && (pr ?? 0) >= ladder[n]) n++;
  return n;
}

// Trophies across all games, from the `pr` map of lifetime point counters.
export function totalTrophies(pr) {
  return GAMES.reduce((a, g) => a + trophyCount(g, pr?.[g]), 0);
}

// Points a finished round is worth (§8.3). Linear: every star costs the same
// inside a difficulty, and a star is worth `difficulty + 1` points — 1 on
// Leicht, 2 on Mittel, 3 on Schwer. A whole tile is therefore 3, 6 or 9.
//
// There used to be a `+3 × difficulty` bonus on the third star, so the first
// two stars were worth a third of the tile and the last one two thirds. It made
// the picker's numbers unexplainable and the star display a lie: three equal
// stars that were not worth equal amounts.
//
// A tile you have already mastered is worth nothing, so no amount of replaying
// buys a trophy.
export function roundPoints({ oldStars = 0, newStars = 0, difficulty = 0 } = {}) {
  if (!(newStars > oldStars)) return 0;
  return (newStars - oldStars) * starValue(difficulty);
}

// What a single star is worth here. The picker prints it as "×2" / "×3": the
// stars are always three, but each one counts double or triple (§10.2).
export const starValue = (difficulty = 0) => clampDifficulty(difficulty) + 1;

// What a tile can still pay. The picker no longer prints this — it shows the
// three stars instead — but the trophy economy is balanced against it, and
// `tests/rewards.test.js` checks the whole collection stays reachable.
export function tilePointsLeft(stars = 0, difficulty = 0) {
  return roundPoints({ oldStars: stars, newStars: 3, difficulty });
}

// The site has exactly ONE number a child collects (§8.3), and it is the star.
//
// There used to be two: a raw star count (three per tile, whatever the
// difficulty) and a weighted "Punkte" counter, `pr`. Mara understood neither,
// and could not see that Mittel and Schwer paid more — the two numbers stood in
// different places and never met. So the weighted counter IS the star count:
// a star won on Leicht counts 1, on Mittel 2, on Schwer 3, which is precisely
// what the picker has always claimed with its "×2 ⭐". The store is unchanged;
// only the word "Punkte" is gone.
export function gameStarsOf(pr, game) {
  const n = pr?.[game];
  return Number.isFinite(n) && n > 0 ? n : 0;
}

export function totalPoints(pr) {
  return GAMES.reduce((a, g) => a + gameStarsOf(pr, g), 0);
}

// Everything the top bar says about the fox (§3.3): the two counters a child
// collects, read from the store.
//
// There used to be a "level" here (`1 + floor(stars / 10)`), then a progress
// bar toward the fox's next piece of clothing. Both were second names for the
// star count, printed beside the star count. What is left is what was actually
// earned: stars, and the trophies they bought.
export function foxInfo() {
  const rewards = getRewards(loadState()); // one state parse, two counters
  return {
    stars: totalPoints(rewards.pr),
    trophies: totalTrophies(rewards.pr),
  };
}

// A region's progress, as a fraction of everything its game can pay.
const fractionOf = (pr, game) => gameStarsOf(pr, game) / MAX_POINTS[game];

// Region visual state (§3.1): base → thriving (≥ 1/3) → mastered (100 %).
export function regionState(pr, game) {
  const frac = fractionOf(pr, game);
  if (frac >= 1) return "mastered";
  if (frac >= 1 / 3) return "thriving";
  return "base";
}

// The Trophy Room is a region too (§3.1): the same base → thriving (≥ 1/3) →
// mastered (100 %) rule, over trophies out of TOTAL_TROPHIES instead of stars
// out of MAX_POINTS.
export function pokalraumState(trophies) {
  if (trophies >= TOTAL_TROPHIES) return "mastered";
  if (trophies >= TOTAL_TROPHIES / 3) return "thriving";
  return "base";
}

// Badge tier for the map star badges: 0 = none, 1 = some stars,
// 2 = >= 1/3 of what the game can pay (gold), 3 = 100 % (glowing).
export function starBadgeTier(pr, game) {
  if (gameStarsOf(pr, game) <= 0) return 0;
  const frac = fractionOf(pr, game);
  return frac >= 1 ? 3 : frac >= 1 / 3 ? 2 : 1;
}

// Progress toward the next trophy of one game (pr = that game's lifetime point
// counter). Returns null once all twelve are earned, or for an unknown game.
export function nextTrophyInfo(game, pr) {
  const ladder = THRESHOLDS[game];
  const earned = trophyCount(game, pr);
  if (!ladder || earned >= ladder.length) return null;
  return { earned, threshold: ladder[earned], remaining: ladder[earned] - (pr ?? 0) };
}

// ---- storage-backed functions ---------------------------------------------

// Called by games at the end of every round (§8). Updates the fox's map
// position and the per-game star counter; returns the trophies the round won.
//
// `streak: undefined` scrubs the daily streak from stores that still carry
// it. It was tracked for a year and rendered nowhere (§8.5 — removed), and
// JSON.stringify drops undefined values, so the field vanishes on the next
// finished round and its bytes go back to the state budget.
export function recordRound(game, { points = 0 }) {
  const pr = { ...(getRewards().pr ?? {}) };
  let newTrophies = [];
  if (points > 0) {
    const before = trophyCount(game, pr[game]);
    pr[game] = (pr[game] ?? 0) + points;
    newTrophies = TROPHIES[game].slice(before, trophyCount(game, pr[game]));
  }
  setRewards({ at: game, pr, streak: undefined });
  return { newTrophies };
}
